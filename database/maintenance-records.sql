CREATE TABLE IF NOT EXISTS health_asset_maintenance_records (
  id CHAR(36) NOT NULL PRIMARY KEY,
  asset_id CHAR(36) NOT NULL,
  asset_tag_snapshot VARCHAR(191) NOT NULL,
  asset_name_snapshot VARCHAR(255) NOT NULL,
  previous_status VARCHAR(50) NOT NULL,
  started_at DATE NOT NULL,
  issue_description TEXT NOT NULL,
  service_provider VARCHAR(255) NULL,
  estimated_cost DECIMAL(12, 2) NULL,
  reference_number VARCHAR(191) NULL,
  status ENUM('Open', 'Completed') NOT NULL DEFAULT 'Open',
  district_snapshot VARCHAR(100) NOT NULL,
  sub_district_snapshot VARCHAR(255) NULL,
  facility_name_snapshot VARCHAR(255) NOT NULL,
  location_snapshot VARCHAR(255) NOT NULL,
  condition_snapshot VARCHAR(50) NOT NULL,
  custodian_name_snapshot VARCHAR(255) NULL,
  custodian_persal_number_snapshot VARCHAR(8) NULL,
  opened_by CHAR(36) NOT NULL,
  opener_name_snapshot VARCHAR(255) NOT NULL,
  opener_persal_number_snapshot VARCHAR(8) NOT NULL,
  opener_role_snapshot VARCHAR(32) NOT NULL,
  opened_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATE NULL,
  work_performed TEXT NULL,
  actual_cost DECIMAL(12, 2) NULL,
  completion_notes TEXT NULL,
  completed_by CHAR(36) NULL,
  completer_name_snapshot VARCHAR(255) NULL,
  completer_persal_number_snapshot VARCHAR(8) NULL,
  completer_role_snapshot VARCHAR(32) NULL,
  recorded_at DATETIME NULL,
  INDEX idx_maintenance_asset_status (asset_id, status),
  INDEX idx_maintenance_district_date (district_snapshot, opened_at),
  CONSTRAINT fk_maintenance_asset
    FOREIGN KEY (asset_id) REFERENCES health_assets(id) ON DELETE RESTRICT,
  CONSTRAINT fk_maintenance_opener
    FOREIGN KEY (opened_by) REFERENCES app_users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_maintenance_completer
    FOREIGN KEY (completed_by) REFERENCES app_users(id) ON DELETE RESTRICT
);
